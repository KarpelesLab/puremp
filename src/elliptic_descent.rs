//! Certified Mordell–Weil ranks over `ℚ` by **descent via 2-isogeny**.
//!
//! This module handles elliptic curves over `ℚ` with a rational 2-torsion point.
//! Moving that point to the origin puts the curve in the form
//!
//! ```text
//! E  : y² = x³ + a·x² + b·x,          a, b ∈ ℤ,  b ≠ 0,  a² − 4b ≠ 0,
//! ```
//!
//! which is the domain of the 2-isogeny `φ : E → E'` onto
//!
//! ```text
//! E' : Y² = X³ − 2a·X² + (a² − 4b)·X
//! ```
//!
//! (with dual `φ̂ : E' → E`, `φ̂ ∘ φ = [2]`). [`TwoIsogenyCurve`] stores `(a, b)`;
//! [`TwoIsogenyCurve::from_short_weierstrass`] converts a short-Weierstrass
//! [`EllipticCurve<Rational>`] with a rational 2-torsion point into this shape.
//!
//! # The descent
//!
//! For a curve `C : y² = x³ + a·x² + b·x` let
//!
//! ```text
//! α_C : C(ℚ) → ℚ*/ℚ*²,   (x, y) ↦ x,   (0, 0) ↦ b,   O ↦ 1.
//! ```
//!
//! This is a homomorphism whose kernel is the image of the dual isogeny, and
//! `d ∈ ℚ*/ℚ*²` lies in its image iff `d` is (the class of) a squarefree divisor of
//! `b` for which the quartic
//!
//! ```text
//! N_d :  w² = d·u⁴ + a·u²v² + (b/d)·v⁴
//! ```
//!
//! has a rational solution with `(u, v) ≠ (0, 0)`; the point is
//! `(d·u²/v², d·u·w/v³)` (Silverman–Tate, *Rational Points on Elliptic Curves*,
//! §III.5; Silverman, *The Arithmetic of Elliptic Curves* (AEC), Prop. X.4.9).
//! The **Selmer group** attached to `α_C` is the set of those `d` for which `N_d`
//! is solvable over `ℝ` and over every `ℚ_p`; it is a finite `𝔽₂`-vector space
//! containing `α_C(C(ℚ))`, and only the primes `p | 2·b·(a² − 4b)` need testing.
//!
//! In AEC's notation the Selmer group computed from `E` (generated by `−1` and
//! the primes of `b`) is `S^(φ̂)(E'/ℚ)`, which contains `E(ℚ)/φ̂(E'(ℚ))`, and the
//! one computed from `E'` (primes of `a² − 4b`) is `S^(φ)(E/ℚ)`, containing
//! `E'(ℚ)/φ(E(ℚ))`. With `r = rank E(ℚ)`, the classical formula
//! (Silverman–Tate §III.6, AEC Prop. X.6.2(c) and its proof)
//!
//! ```text
//! 2^r = #α_E(E(ℚ)) · #α_E'(E'(ℚ)) / 4
//! ```
//!
//! gives `r = dim α_E + dim α_E' − 2` and hence the upper bound
//!
//! ```text
//! r ≤ U := dim S^(φ)(E/ℚ) + dim S^(φ̂)(E'/ℚ) − 2,
//! ```
//!
//! with equality iff `Ш(E/ℚ)[φ] = Ш(E'/ℚ)[φ̂] = 0`. A lower bound comes from
//! global solutions of the quartics found by a bounded search: every solution
//! found exhibits an element of the image of `α_E` (resp. `α_E'`), so if the
//! found classes span spaces of dimensions `f`, `f'`, then `r ≥ f + f' − 2`.
//!
//! # Local solubility
//!
//! Over `ℝ`, `N_d` is solvable iff `d > 0`, or `b/d > 0`, or `a > 0` and
//! `a² − 4b > 0` (a positive root of `d·X² + a·X + b/d`).
//!
//! Over `ℚ_p` every point of `ℙ¹(ℚ_p)` is `(x : 1)` with `x ∈ ℤ_p` or `(1 : p·z)`
//! with `z ∈ ℤ_p`, so solubility reduces to deciding whether a polynomial
//! `g ∈ ℤ[x]` of degree ≤ 4 with distinct roots takes a square value in `ℚ_p` on
//! `ℤ_p`. This is decided **exactly** by a recursion over residue discs
//! `x₀ + pⁿℤ_p` in the style of the local solubility tests of Merriman–Siksek–
//! Smart and Cremona (*Algorithms for Modular Elliptic Curves*, §3.5–3.6):
//!
//! - **Hensel**: if `v(g(x₀)) > 2·v(g'(x₀))` and `v(g(x₀)) − v(g'(x₀)) ≥ n`, a root
//!   of `g` lies in the disc, and a zero is a square;
//! - **odd `p`**: writing `g(x₀ + pⁿt) = p^μ·(h̄(t) + p·…)` with `h̄ ≢ 0 mod p`, a
//!   residue `t` with `h̄(t) ≠ 0` decides its sub-disc (square iff `μ` even and
//!   `h̄(t)` a quadratic residue); only roots of `h̄` mod `p` need refinement. For
//!   large `p`, the existence of a good residue is read off from whether `h̄` is a
//!   constant times a square (Weil's bound `|Σ χ(h̄(t))| ≤ 3√p` handles the rest)
//!   and roots mod `p` come from Cantor–Zassenhaus, so the cost is polynomial in
//!   `log p`;
//! - **`p = 2`**: when every Taylor term of order ≥ 1 on the disc has valuation
//!   at least `v(g(x₀)) + 3`, the class of `g` mod squares is constant on the disc
//!   (a 2-adic unit is a square iff it is `≡ 1 mod 8`); otherwise the disc is
//!   halved.
//!
//! Since `g` has distinct roots the recursion terminates: away from the roots the
//! valuation of `g` is bounded and the Taylor terms eventually dominate, and near
//! a simple root the Hensel test fires. All arithmetic is exact integer
//! arithmetic; there is no precision guess. A generous depth cap exists only as a
//! guard: if it were ever hit, the class is conservatively kept in the Selmer
//! group (so the upper bound stays valid) and the descent is flagged inexact,
//! which disables the [2-converse](RankMethod::TwoConverse) path.
//!
//! # Certificates
//!
//! [`TwoIsogenyCurve::certified_rank`] returns a [`RankCertificate`]:
//!
//! - [`RankMethod::SelmerBound`] — `U = 0`, so `r = 0` (classical);
//! - [`RankMethod::PointsMeetSelmerBound`] — the independent points found give
//!   `r ≥ U` (classical);
//! - [`RankMethod::TwoConverse`] — `U = 1` and no point of infinite order was
//!   found; `r = 1` follows from a **2026 unrefereed preprint** (see below);
//! - otherwise [`RankCertificate::Bounds`].
//!
//! ## The 2-converse path
//!
//! Put `d₂(E) = dim Sel₂(E/ℚ) − dim E(ℚ)[2]`. OpenAI, *Goldfeld's analytic
//! density conjecture and the 2-converse for elliptic curves* (preprint,
//! September 23, 2026), Corollary "A finite Selmer criterion" (with Lemma
//! "Finite descent and corank"), proves: **if `d₂(E) ∈ {0, 1}` then
//! `ord_{s=1} L(E, s) = rank E(ℚ) = d₂(E)`, `Ш(E/ℚ)` is finite and
//! `Ш(E/ℚ)[2^∞] = 0`.** (The rational-two-torsion case is also treated
//! separately in OpenAI, *A pointwise 2-converse for elliptic curves with
//! rational two-torsion*, preprint, September 24, 2026, Theorem 1.1, stated for
//! the full 2^∞-Selmer corank.) These results are recent and **not refereed**;
//! a certificate with [`RankMethod::TwoConverse`] is only as reliable as that
//! preprint, which is why the method is reported separately.
//!
//! The 2-isogeny Selmer groups do not determine `Sel₂(E)` exactly, so the
//! criterion is applied through the following classical inequalities. From the
//! Kummer sequence, `d₂(E) = r + dim Ш(E)[2]`; from
//! `0 → Ш(E)[φ] → Ш(E)[2] →φ Ш(E')[φ̂]`, `dim Ш(E)[2] ≤ dim Ш(E)[φ] + dim Ш(E')[φ̂]`;
//! hence `d₂(E) ≤ r + dim Ш(E)[φ] + dim Ш(E')[φ̂] = U`, and symmetrically
//! `d₂(E') ≤ U`. When the Selmer groups are computed exactly and `U = 1`, both
//! `d₂(E)` and `d₂(E')` lie in `{0, 1}`; the corollary applied to `E` and to `E'`
//! gives `Ш(E)[2^∞] = Ш(E')[2^∞] = 0`, so `r = U − dim Ш(E)[φ] − dim Ш(E')[φ̂] = 1`
//! (and then `d₂(E) = 1` and the analytic rank is 1). Only `U = 1` uses the
//! preprint; `U = 0 ⇒ r = 0` is classical.
//!
//! # Clean-room provenance
//!
//! Silverman, *The Arithmetic of Elliptic Curves* §X.4 and §X.6; Silverman–Tate,
//! *Rational Points on Elliptic Curves* §III.5–III.6; Cremona, *Algorithms for
//! Modular Elliptic Curves* §3.5–3.6; Cohen, *A Course in Computational Algebraic
//! Number Theory* §3.4 (Cantor–Zassenhaus); the preprints cited above. No
//! third-party source code was consulted.

