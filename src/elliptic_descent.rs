/// Distinct primes of `|n|`, sorted.
fn distinct_primes(n: &Int) -> Vec<Int> {
    n.factor_exponents().into_iter().map(|(p, _)| p).collect()
}

/// The squarefree integer with sign bit 0 and prime bits 1.. of `mask`.
fn mask_to_int(mask: u64, primes: &[Int]) -> Int {
    let mut d = if mask & 1 == 1 {
        Int::MINUS_ONE
    } else {
        Int::ONE
    };
    for (i, p) in primes.iter().enumerate() {
        if mask >> (i + 1) & 1 == 1 {
            d = d.mul(p);
        }
    }
    d
}

/// Inserts `v` into an `𝔽₂` xor-basis; returns `true` if it was independent.
fn xor_basis_insert(basis: &mut Vec<u64>, mut v: u64) -> bool {
    for &b in basis.iter() {
        v = v.min(v ^ b);
    }
    if v == 0 {
        return false;
    }
    basis.push(v);
    basis.sort_unstable_by(|x, y| y.cmp(x));
    true
}

fn in_span(basis: &[u64], mut v: u64) -> bool {
    for &b in basis {
        v = v.min(v ^ b);
    }
    v == 0
}

/// Selmer group of `α_C` for `C : y² = x³ + a x² + b x`, plus global images.
fn selmer_data(a: &Int, b: &Int, search_bound: u32) -> SelmerData {
    let primes = distinct_primes(b);
    assert!(
        primes.len() < 63,
        "2-isogeny descent: too many prime factors"
    );
    let disc = a.square().sub(&b.mul_2k(2));
    let mut bad = primes.clone();
    bad.extend(distinct_primes(&disc));
    bad.push(Int::from(2));
    bad.sort();
    bad.dedup();

    let count = 1u64 << (primes.len() + 1);
    let mut members: Vec<u64> = Vec::new();
    let mut exact = true;
    for mask in 0..count {
        let d = mask_to_int(mask, &primes);
        let e = b.div_exact(&d);
        if !quartic_is_real_soluble(&d, a, &e) {
            continue;
        }
        let mut ok = true;
        let mut undecided = false;
        for p in &bad {
            match quartic_is_locally_soluble(&d, a, &e, p) {
                Some(true) => {}
                Some(false) => {
                    ok = false;
                    break;
                }
                None => undecided = true,
            }
        }
        if ok {
            if undecided {
                exact = false;
            }
            members.push(mask);
        }
    }
    // Span (equals the member set when exact; a valid over-approximation
    // otherwise).
    let mut sel_basis: Vec<u64> = Vec::new();
    for &m in &members {
        xor_basis_insert(&mut sel_basis, m);
    }
    let selmer_dim = sel_basis.len() as u32;
    debug_assert!(!exact || members.len() as u64 == 1u64 << selmer_dim);

    // Global points: 1 and b are always images (O and (0, 0)).
    let mut img: Vec<u64> = Vec::new();
    let b_mask = int_to_mask(b, &primes);
    xor_basis_insert(&mut img, b_mask);
    for &m in &members {
        if in_span(&img, m) {
            continue;
        }
        let d = mask_to_int(m, &primes);
        let e = b.div_exact(&d);
        if quartic_has_global_point(&d, a, &e, search_bound) {
            xor_basis_insert(&mut img, m);
        }
    }
    debug_assert!(img.iter().all(|&m| in_span(&sel_basis, m)));
    SelmerData {
        selmer: members.iter().map(|&m| mask_to_int(m, &primes)).collect(),
        selmer_dim,
        image_basis: img.iter().map(|&m| mask_to_int(m, &primes)).collect(),
        exact,
    }
}

/// The mask of the squarefree part of `n` (whose primes all lie in `primes`).
fn int_to_mask(n: &Int, primes: &[Int]) -> u64 {
    let mut mask = u64::from(n.is_negative());
    for (i, p) in primes.iter().enumerate() {
        let mut k = 0u32;
        let mut m = n.abs();
        while let Some((q, r)) = m.div_rem(p) {
            if !r.is_zero() {
                break;
            }
            m = q;
            k += 1;
        }
        if !k.is_multiple_of(2) {
            mask |= 1 << (i + 1);
        }
    }
    mask
}

/// Searches `w² = d u⁴ + a u² v² + e v⁴` for `0 ≤ u ≤ B`, `1 ≤ v ≤ B` coprime
/// (and `(u, v) = (1, 0)`).
fn quartic_has_global_point(d: &Int, a: &Int, e: &Int, bound: u32) -> bool {
    if d.sqrt_exact().is_some() {
        return true; // (u, v) = (1, 0)
    }
    if bound == 0 {
        return false;
    }
    let bound_u = u128::from(bound);
    let small: Option<Vec<i128>> = [d, a, e].iter().map(|c| c.to_i128()).collect();
    if let Some(c) = small {
        let cmax = c.iter().map(|x| x.unsigned_abs()).max().unwrap_or(0);
        let b4 = bound_u.pow(4);
        if cmax.checked_mul(3 * b4).is_some_and(|m| m < (1u128 << 126)) {
            let (d, a, e) = (c[0], c[1], c[2]);
            for v in 1..=i128::from(bound) {
                let v2 = v * v;
                let ev4 = e * v2 * v2;
                for u in 0..=i128::from(bound) {
                    if gcd_u(u as u128, v as u128) != 1 {
                        continue;
                    }
                    let u2 = u * u;
                    let val = d * u2 * u2 + a * u2 * v2 + ev4;
                    if val >= 0 && is_square_u128(val as u128) {
                        return true;
                    }
                }
            }
            return false;
        }
    }
    for v in 1..=bound {
        let vi = Int::from(v);
        let v2 = vi.square();
        let ev4 = e.mul(&v2.square());
        for u in 0..=bound {
            if gcd_u(u128::from(u), u128::from(v)) != 1 {
                continue;
            }
            let u2 = Int::from(u).square();
            let val = d.mul(&u2.square()).add(&a.mul(&u2).mul(&v2)).add(&ev4);
            if val.sqrt_exact().is_some() {
                return true;
            }
        }
    }
    false
}

fn gcd_u(mut a: u128, mut b: u128) -> u128 {
    while b != 0 {
        let t = a % b;
        a = b;
        b = t;
    }
    a
}

fn is_square_u128(n: u128) -> bool {
    // Quick residue filter mod 64.
    if (0x0202_0212_0203_0213u64 >> (n & 63)) & 1 == 0 {
        return false;
    }
    let r = n.isqrt();
    r * r == n
}

