/// Default half-width of the search box used for global points on the quartics.
pub const DEFAULT_SEARCH_BOUND: u32 = 400;

/// An elliptic curve `y² = x³ + a·x² + b·x` over `ℚ` with integer `a`, `b`
/// (`b ≠ 0`, `a² − 4b ≠ 0`), i.e. a curve with the rational 2-torsion point
/// `(0, 0)`. See the [module documentation](self).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TwoIsogenyCurve {
    a: Int,
    b: Int,
}

/// The change of variables produced by
/// [`TwoIsogenyCurve::from_short_weierstrass`]: a point `(x, y)` of the short
/// Weierstrass curve maps to `(X, Y) = (λ²·(x − x₀), λ³·y)` on the
/// [`TwoIsogenyCurve`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct WeierstrassToTwoIsogeny {
    /// The rational root `x₀` of `x³ + A·x + B` that is moved to the origin.
    pub x_shift: Rational,
    /// The positive integer scale `λ`.
    pub scale: Int,
}

impl WeierstrassToTwoIsogeny {
    /// Maps an affine point `(x, y)` of the short Weierstrass model to the
    /// [`TwoIsogenyCurve`] model.
    pub fn map_point(&self, x: &Rational, y: &Rational) -> (Rational, Rational) {
        let l2 = Rational::from_integer(self.scale.square());
        let l3 = Rational::from_integer(self.scale.pow(3));
        (x.sub(&self.x_shift).mul(&l2), y.mul(&l3))
    }
}

/// How a [`RankCertificate::Proven`] rank was established.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RankMethod {
    /// The 2-isogeny Selmer bound is `0`, so the rank is `0` (classical:
    /// Silverman–Tate §III.6, AEC §X.6).
    SelmerBound,
    /// Points found by search span a subgroup whose rank equals the Selmer upper
    /// bound (classical).
    PointsMeetSelmerBound,
    /// The Selmer bound is `1` and the rank equals `1` by the 2-converse /
    /// finite Selmer criterion of the **unrefereed 2026 preprint** cited in the
    /// [module documentation](self#the-2-converse-path). Callers that only accept
    /// classical results should treat this as `Bounds { lower: 0, upper: 1 }`.
    TwoConverse,
}

/// The outcome of [`TwoIsogenyCurve::certified_rank`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RankCertificate {
    /// The rank is exactly `rank`, established by `method`.
    Proven {
        /// The Mordell–Weil rank of `E(ℚ)`.
        rank: u32,
        /// The argument that proves it.
        method: RankMethod,
    },
    /// Rigorous bounds `lower ≤ rank E(ℚ) ≤ upper` that do not meet.
    Bounds {
        /// Lower bound from independent points found by search.
        lower: u32,
        /// Upper bound `dim S^(φ) + dim S^(φ̂) − 2`.
        upper: u32,
    },
}

impl RankCertificate {
    /// The proven rank, if any (including [`RankMethod::TwoConverse`]).
    pub fn rank(&self) -> Option<u32> {
        match self {
            RankCertificate::Proven { rank, .. } => Some(*rank),
            RankCertificate::Bounds { .. } => None,
        }
    }
}

/// One side of a 2-isogeny descent: the Selmer group attached to
/// `α_C : C(ℚ) → ℚ*/ℚ*²` and the part of the image `α_C(C(ℚ))` exhibited by
/// global points.
#[derive(Clone, Debug)]
pub struct SelmerData {
    /// All elements of the Selmer group, as squarefree integers (`1` included).
    pub selmer: Vec<Int>,
    /// `dim_𝔽₂` of the Selmer group.
    pub selmer_dim: u32,
    /// A basis of the subspace spanned by the classes `d` for which a global
    /// point of `N_d` was found (as squarefree integers).
    pub image_basis: Vec<Int>,
    /// Whether every local test was decided (always `true` in practice).
    pub exact: bool,
}

/// The full data of a 2-isogeny descent on `E` and `E'`.
#[derive(Clone, Debug)]
pub struct TwoIsogenyDescent {
    /// Data from `E : y² = x³ + a·x² + b·x` (generated by `−1` and the primes of
    /// `b`): this Selmer group is `S^(φ̂)(E'/ℚ)` and the image is
    /// `α_E(E(ℚ)) ≅ E(ℚ)/φ̂(E'(ℚ))`.
    pub curve: SelmerData,
    /// Data from `E' : y² = x³ − 2a·x² + (a² − 4b)·x`: Selmer group
    /// `S^(φ)(E/ℚ)` and image `α_E'(E'(ℚ)) ≅ E'(ℚ)/φ(E(ℚ))`.
    pub isogenous: SelmerData,
    /// `rank E(ℚ) ≥ lower` from the found points.
    pub lower: u32,
    /// `rank E(ℚ) ≤ upper = dim S^(φ) + dim S^(φ̂) − 2`.
    pub upper: u32,
}

impl TwoIsogenyCurve {
    /// The curve `y² = x³ + a·x² + b·x`, or `None` if it is singular
    /// (`b = 0` or `a² − 4b = 0`).
    pub fn new(a: Int, b: Int) -> Option<TwoIsogenyCurve> {
        if b.is_zero() || a.square() == b.mul_2k(2) {
            return None;
        }
        Some(TwoIsogenyCurve { a, b })
    }

    /// The coefficient `a`.
    pub fn a(&self) -> &Int {
        &self.a
    }

    /// The coefficient `b`.
    pub fn b(&self) -> &Int {
        &self.b
    }

    /// The 2-isogenous curve `E' : y² = x³ − 2a·x² + (a² − 4b)·x`.
    pub fn isogenous(&self) -> TwoIsogenyCurve {
        TwoIsogenyCurve {
            a: self.a.mul_2k(1).neg(),
            b: self.a.square().sub(&self.b.mul_2k(2)),
        }
    }

    /// The short Weierstrass model `y² = x³ + A·x + B` obtained by `x ↦ x − a/3`.
    pub fn to_short_weierstrass(&self) -> EllipticCurve<Rational> {
        // x³ + a x² + b x with x = t − a/3: A = b − a²/3, B = 2a³/27 − ab/3.
        let a = Rational::from_integer(self.a.clone());
        let b = Rational::from_integer(self.b.clone());
        let three = Rational::from_integer(Int::from(3));
        let a2 = a.mul(&a);
        let big_a = b.sub(&a2.div(&three));
        let big_b = a2
            .mul(&a)
            .mul(&Rational::new(Int::from(2), Int::from(27)))
            .sub(&a.mul(&b).div(&three));
        EllipticCurve::new(big_a, big_b).expect("non-singular by construction")
    }

    /// Moves a short Weierstrass curve `y² = x³ + A·x + B` over `ℚ` with a
    /// rational 2-torsion point into the form `y² = x³ + a·x² + b·x` with integer
    /// `a`, `b`. Returns `None` if `x³ + A·x + B` has no rational root.
    ///
    /// If there are three rational roots, the smallest is used.
    pub fn from_short_weierstrass(
        curve: &EllipticCurve<Rational>,
    ) -> Option<(TwoIsogenyCurve, WeierstrassToTwoIsogeny)> {
        let (ca, cb) = (curve.a(), curve.b());
        let den = ca.denominator().lcm(cb.denominator());
        // x = X/den: X³ + (A·den²)·X + B·den³, a monic integer cubic.
        let p = ca.mul(&Rational::from_integer(den.square())).to_integer()?;
        let q = cb.mul(&Rational::from_integer(den.pow(3))).to_integer()?;
        let root = integer_roots_depressed_cubic(&p, &q).into_iter().next()?;
        let x0 = Rational::new(root, den);
        // Translate: (x + x0)³ + A(x + x0) + B = x³ + 3x0·x² + (3x0² + A)·x.
        let three = Rational::from_integer(Int::from(3));
        let ar = three.mul(&x0);
        let br = three.mul(&x0).mul(&x0).add(ca);
        let lambda = ar.denominator().lcm(br.denominator());
        let a = ar
            .mul(&Rational::from_integer(lambda.square()))
            .to_integer()?;
        let b = br
            .mul(&Rational::from_integer(lambda.pow(4)))
            .to_integer()?;
        let c = TwoIsogenyCurve::new(a, b)?;
        Some((
            c,
            WeierstrassToTwoIsogeny {
                x_shift: x0,
                scale: lambda,
            },
        ))
    }

    /// Runs the 2-isogeny descent on `E` and `E'`, searching for global points
    /// on the quartics `N_d` with `|u|, |v| ≤ search_bound`.
    pub fn two_isogeny_descent(&self, search_bound: u32) -> TwoIsogenyDescent {
        let iso = self.isogenous();
        let curve = selmer_data(&self.a, &self.b, search_bound);
        let isogenous = selmer_data(&iso.a, &iso.b, search_bound);
        let upper = (curve.selmer_dim + isogenous.selmer_dim).saturating_sub(2);
        let found = curve.image_basis.len() as u32 + isogenous.image_basis.len() as u32;
        let lower = found.saturating_sub(2);
        TwoIsogenyDescent {
            curve,
            isogenous,
            lower,
            upper,
        }
    }

    /// The certified rank with the default point-search bound
    /// [`DEFAULT_SEARCH_BOUND`]. See [`RankCertificate`] and the
    /// [module documentation](self#certificates).
    pub fn certified_rank(&self) -> RankCertificate {
        self.certified_rank_with_search_bound(DEFAULT_SEARCH_BOUND)
    }

    /// The certified rank, searching for points with `|u|, |v| ≤ search_bound`.
    /// The returned certificate is never wrong; only
    /// [`RankMethod::TwoConverse`] depends on the unrefereed 2026 preprint.
    pub fn certified_rank_with_search_bound(&self, search_bound: u32) -> RankCertificate {
        certificate_from_descent(&self.two_isogeny_descent(search_bound))
    }
}

/// Turns descent data into a [`RankCertificate`].
pub fn certificate_from_descent(desc: &TwoIsogenyDescent) -> RankCertificate {
    let (lower, upper) = (desc.lower, desc.upper);
    debug_assert!(lower <= upper, "2-descent: lower bound exceeds upper bound");
    if lower > upper {
        // Inconsistent data (an internal bug): never certify anything from it.
        return RankCertificate::Bounds { lower, upper };
    }
    if upper == 0 {
        return RankCertificate::Proven {
            rank: 0,
            method: RankMethod::SelmerBound,
        };
    }
    if lower == upper {
        return RankCertificate::Proven {
            rank: upper,
            method: RankMethod::PointsMeetSelmerBound,
        };
    }
    // U = 1 with exact Selmer groups: d₂(E), d₂(E') ≤ 1, so the finite Selmer
    // criterion kills Ш(E)[2^∞] and Ш(E')[2^∞], forcing rank = U = 1.
    if upper == 1 && desc.curve.exact && desc.isogenous.exact {
        return RankCertificate::Proven {
            rank: 1,
            method: RankMethod::TwoConverse,
        };
    }
    RankCertificate::Bounds { lower, upper }
}

impl EllipticCurve<Rational> {
    /// Certified rank of a curve over `ℚ` with a rational 2-torsion point, via
    /// [`TwoIsogenyCurve::from_short_weierstrass`] and
    /// [`TwoIsogenyCurve::certified_rank`]. `None` if the cubic has no rational
    /// root (no rational 2-torsion).
    pub fn certified_rank(&self) -> Option<RankCertificate> {
        TwoIsogenyCurve::from_short_weierstrass(self).map(|(c, _)| c.certified_rank())
    }
}

/// Whether `w² = d·u⁴ + a·u²v² + e·v⁴` has a real solution with `(u, v) ≠ 0`.
/// Requires `d·e ≠ 0`.
pub fn quartic_is_real_soluble(d: &Int, a: &Int, e: &Int) -> bool {
    d.is_positive() || e.is_positive() || (a.is_positive() && a.square() > d.mul(e).mul_2k(2))
}

/// Whether `w² = d·u⁴ + a·u²v² + e·v⁴` has a solution over `ℚ_p` with
/// `(u, v) ≠ (0, 0)`, for a prime `p`. Requires `d·e·(a² − 4de) ≠ 0`.
///
/// Returns `None` only if the internal recursion guard is hit (never observed;
/// the recursion provably terminates).
pub fn quartic_is_locally_soluble(d: &Int, a: &Int, e: &Int, p: &Int) -> Option<bool> {
    assert!(
        !d.is_zero() && !e.is_zero() && a.square() != d.mul(e).mul_2k(2),
        "quartic must have distinct roots"
    );
    let cap = 64 + 4 * [d, a, e].iter().map(|c| c.bit_len()).max().unwrap_or(0) + 8 * p.bit_len();
    let zero = Int::ZERO;
    // Chart (x : 1): g(x) = d x⁴ + a x² + e.
    let g1 = [e.clone(), zero.clone(), a.clone(), zero.clone(), d.clone()];
    // Chart (1 : p z): g(z) = d + a p² z² + e p⁴ z⁴.
    let p2 = p.square();
    let g2 = [
        d.clone(),
        zero.clone(),
        a.mul(&p2),
        zero,
        e.mul(&p2.square()),
    ];
    let mut unknown = false;
    for g in [&g1, &g2] {
        match zp_square_value(g, p, &Int::ZERO, 0, cap) {
            Some(true) => return Some(true),
            Some(false) => {}
            None => unknown = true,
        }
    }
    if unknown { None } else { Some(false) }
}

